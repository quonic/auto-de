#!/usr/bin/env python3
"""Convert X11 misc-fixed PCF fonts to an embedded Odin glyph table.

Dev-time tool only (output is committed). Usage:
    tools/fontgen.py OUT.odin NAME=path/to/font.pcf.gz [NAME=...]

Emits, per font, a `Font` value with Latin-1 glyphs 0x20..0xFF as row bitmaps
(one u16 per row, bit 15 = leftmost pixel).
"""
import gzip
import struct
import sys

PCF_PROPERTIES = 1 << 0
PCF_METRICS = 1 << 2
PCF_BITMAPS = 1 << 3
PCF_BDF_ENCODINGS = 1 << 5
PCF_COMPRESSED_METRICS = 0x100


def read_pcf(path):
    data = gzip.open(path).read() if path.endswith(".gz") else open(path, "rb").read()
    assert data[:4] == b"\x01fcp", "not a PCF file"
    (count,) = struct.unpack_from("<I", data, 4)
    tables = {}
    for i in range(count):
        ttype, fmt, size, offset = struct.unpack_from("<IIII", data, 8 + i * 16)
        tables[ttype] = (fmt, offset)

    def endian(fmt):
        return ">" if fmt & 4 else "<"

    # properties
    fmt, off = tables[PCF_PROPERTIES]
    off += 4
    e = endian(fmt)
    (nprops,) = struct.unpack_from(e + "I", data, off)
    props_raw = [struct.unpack_from(e + "IBI", data, off + 4 + i * 9) for i in range(nprops)]
    pad = (nprops & 3) and (4 - (nprops & 3))
    str_off = off + 4 + nprops * 9 + pad + 4
    def cstr(o):
        end = data.index(b"\0", str_off + o)
        return data[str_off + o:end].decode("latin-1")
    props = {}
    for name_off, is_str, value in props_raw:
        props[cstr(name_off)] = cstr(value) if is_str else value

    # metrics
    fmt, off = tables[PCF_METRICS]
    off += 4
    e = endian(fmt)
    metrics = []
    if fmt & PCF_COMPRESSED_METRICS:
        (n,) = struct.unpack_from(e + "H", data, off)
        for i in range(n):
            lsb, rsb, width, asc, desc = (b - 0x80 for b in data[off + 2 + i * 5: off + 7 + i * 5])
            metrics.append((lsb, rsb, width, asc, desc))
    else:
        (n,) = struct.unpack_from(e + "I", data, off)
        for i in range(n):
            lsb, rsb, width, asc, desc, _ = struct.unpack_from(e + "hhhhhH", data, off + 4 + i * 12)
            metrics.append((lsb, rsb, width, asc, desc))

    # bitmaps
    fmt, off = tables[PCF_BITMAPS]
    off += 4
    e = endian(fmt)
    (nglyphs,) = struct.unpack_from(e + "I", data, off)
    offsets = struct.unpack_from(e + "%dI" % nglyphs, data, off + 4)
    sizes = struct.unpack_from(e + "4I", data, off + 4 + nglyphs * 4)
    bitmap_base = off + 4 + nglyphs * 4 + 16
    glyph_pad = 1 << (fmt & 3)
    msbit_first = bool(fmt & 8)
    assert msbit_first, "LSB-first bitmaps not supported"

    def glyph_rows(i):
        lsb, rsb, width, asc, desc = metrics[i]
        w = rsb - lsb
        h = asc + desc
        stride = ((w + glyph_pad * 8 - 1) // (glyph_pad * 8)) * glyph_pad
        rows = []
        base = bitmap_base + offsets[i]
        for r in range(h):
            bits = 0
            for c in range(w):
                byte = data[base + r * stride + c // 8]
                if byte & (0x80 >> (c % 8)):
                    bits |= 1 << c
            rows.append(bits)
        return lsb, asc, w, rows

    # encodings
    fmt, off = tables[PCF_BDF_ENCODINGS]
    off += 4
    e = endian(fmt)
    min_b2, max_b2, min_b1, max_b1, default = struct.unpack_from(e + "5H", data, off)
    ncols = max_b2 - min_b2 + 1
    idx_base = off + 10

    def glyph_index(code):
        b1, b2 = code >> 8, code & 0xFF
        if not (min_b1 <= b1 <= max_b1 and min_b2 <= b2 <= max_b2):
            return None
        (g,) = struct.unpack_from(e + "H", data, idx_base + ((b1 - min_b1) * ncols + (b2 - min_b2)) * 2)
        return None if g == 0xFFFF else g

    return props, metrics, glyph_rows, glyph_index


def main():
    out_path = sys.argv[1]
    lines = [
        "// Code generated by tools/fontgen.py from X11 misc-fixed fonts. DO NOT EDIT.",
        "// Source fonts are public domain (\"Public domain font.  Share and enjoy.\").",
        "",
        "package render",
        "",
    ]
    for spec in sys.argv[2:]:
        name, path = spec.split("=", 1)
        props, metrics, glyph_rows, glyph_index = read_pcf(path)
        copyright = props.get("COPYRIGHT", "")
        assert "Public domain" in copyright, f"{path}: unexpected license {copyright!r}"
        ascent = props.get("FONT_ASCENT", max(m[3] for m in metrics))
        descent = props.get("FONT_DESCENT", max(m[4] for m in metrics))
        height = ascent + descent
        cell_w = max(m[2] for m in metrics)
        glyphs = []
        for code in range(0x20, 0x100):
            g = glyph_index(code)
            rows = [0] * height
            if g is not None:
                lsb, asc, w, grows = glyph_rows(g)
                for r, bits in enumerate(grows):
                    y = ascent - asc + r
                    if 0 <= y < height:
                        v = 0
                        for c in range(w):
                            if bits & (1 << c):
                                x = lsb + c
                                if 0 <= x < 16:
                                    v |= 0x8000 >> x
                        rows[y] = v
            glyphs.extend(rows)
        lines.append(f"// {props.get('FONT', name)}")
        lines.append(f"{name} := Font{{")
        lines.append(f"\tcell_w = {cell_w},")
        lines.append(f"\theight = {height},")
        lines.append(f"\tascent = {ascent},")
        lines.append(f"\tfirst = 0x20,")
        lines.append(f"\tlast = 0xff,")
        lines.append("\trows = {")
        for i in range(0, len(glyphs), height):
            code = 0x20 + i // height
            row = ", ".join("0x%04x" % v for v in glyphs[i:i + height])
            lines.append(f"\t\t{row}, // 0x{code:02x}")
        lines.append("\t},")
        lines.append("}")
        lines.append("")
    open(out_path, "w").write("\n".join(lines))


if __name__ == "__main__":
    main()
